-- DIEUDONNE MUSIC: Supabase SQL setup
-- Run in Supabase Dashboard > SQL Editor. Review policies before using in production.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.media (
  id bigint generated by default as identity primary key,
  title text not null,
  artist text,
  type text not null check (type in ('music','video')),
  file_url text not null,
  cover_url text,
  uploaded_by uuid references auth.users(id) on delete set null,
  published boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.media enable row level security;

-- Users can read their own profile; admins can read profiles for role management.
create policy "read own profile" on public.profiles
for select to authenticated using (id = auth.uid());

create policy "public read published media" on public.media
for select to anon, authenticated using (published = true);

create policy "admin insert media" on public.media
for insert to authenticated
with check (uploaded_by = auth.uid() and exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'
));

create policy "admin update media" on public.media
for update to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

create policy "admin delete media" on public.media
for delete to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

-- Create Storage buckets named "media" and "covers" in Storage dashboard.
-- Set them public if you want public playback/download. This is suitable only for files
-- you have permission to share. For private files, use private buckets + signed URLs.
-- Storage upload policies: allow authenticated admin only. Example policies:
create policy "admin upload media files" on storage.objects
for insert to authenticated
with check (bucket_id in ('media','covers') and exists (
  select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'
));

create policy "public read media files" on storage.objects
for select to anon, authenticated
using (bucket_id in ('media','covers'));

